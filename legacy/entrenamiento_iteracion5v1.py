def evaluate_dataset(dataset_dir, class_names):
    """Audita el dataset sin modificar ni mover archivos."""
    files_by_class = {}
    valid_files_by_class = defaultdict(list)
    invalid_files = []
    dimensions = Counter()
    formats = Counter()
    hashes = defaultdict(list)

    for class_name in class_names:
        class_dir = dataset_dir / class_name
        image_files = sorted(
            path for path in class_dir.iterdir()
            if path.is_file() and path.suffix.lower() in SUPPORTED_EXTENSIONS
        )
        files_by_class[class_name] = image_files

        for image_path in image_files:
            try:
                with Image.open(image_path) as image:
                    image.verify()
                with Image.open(image_path) as image:
                    dimensions[image.size] += 1
                    formats[(image.format or image_path.suffix).upper()] += 1

                digest = hashlib.sha256(image_path.read_bytes()).hexdigest()
                hashes[digest].append(image_path)
                valid_files_by_class[class_name].append(image_path)
            except (UnidentifiedImageError, OSError, ValueError) as error:
                invalid_files.append((image_path, str(error)))

    counts = {name: len(valid_files_by_class[name]) for name in class_names}
    duplicate_groups = [paths for paths in hashes.values() if len(paths) > 1]
    total = sum(counts.values())
    if total == 0:
        raise ValueError(
            "No se encontraron imágenes compatibles. Extensiones admitidas: "
            f"{sorted(SUPPORTED_EXTENSIONS)}"
        )

    smallest = min(counts.values(), default=0)
    largest = max(counts.values(), default=0)
    imbalance_ratio = largest / smallest if smallest else float("inf")

    print("\n=== AUDITORÍA DEL DATASET ===")
    print(f"Ruta: {dataset_dir}")
    print(f"Total de imágenes válidas: {total}")
    for name, count in counts.items():
        percentage = (100 * count / total) if total else 0
        print(f"  {name}: {count} ({percentage:.2f}%)")
    print(f"Relación clase mayor/menor: {imbalance_ratio:.2f}")
    print(f"Imágenes ilegibles: {len(invalid_files)}")
    print(f"Grupos de duplicados exactos: {len(duplicate_groups)}")
    print("Formatos:", dict(formats))
    print("Dimensiones más frecuentes:", dimensions.most_common(10))

    if invalid_files:
        print("\nArchivos ilegibles:")
        for path, error in invalid_files[:20]:
            print(f"  {path}: {error}")

    if duplicate_groups:
        print("\nPrimeros grupos de duplicados exactos:")
        for group in duplicate_groups[:10]:
            print("  " + " | ".join(str(path.relative_to(dataset_dir)) for path in group))

    return counts, valid_files_by_class, invalid_files, duplicate_groups


