def augment_class_images(input_dir, output_class_dir, target_count):
    os.makedirs(output_class_dir, exist_ok=True)
    images = os.listdir(input_dir)
    current_count = len(images)

    # Copiar imágenes originales
    for img_name in images:
        src = os.path.join(input_dir, img_name)
        dst = os.path.join(output_class_dir, img_name)
        shutil.copy2(src, dst)

    if current_count >= target_count:
        print(f"{output_class_dir} ya tiene suficientes imágenes.")
        return

    print(f"Augmentando {output_class_dir} de {current_count} a {target_count} imágenes...")
    generated = 0
    while current_count + generated < target_count:
        img_name = random.choice(images)
        img_path = os.path.join(input_dir, img_name)

        img = load_img(img_path, target_size=IMG_SIZE)
        x = img_to_array(img)
        x = x.reshape((1,) + x.shape)

        for batch in datagen.flow(x, batch_size=1):
            new_img_name = f"aug_{generated}_{img_name}"
            save_img(os.path.join(output_class_dir, new_img_name), batch[0])
            generated += 1
            break  # Genera una sola imagen por iteración

    print(f"Generadas {generated} imágenes para {output_class_dir}")

